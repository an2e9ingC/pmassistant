def _all_virtual(nodes):
    """遍历所有虚拟节点（dict），生成 (key, node)。"""
    for n in nodes:
        yield n["key"], n
        for c in n["children"]:
            if isinstance(c, dict):
                yield from _all_virtual([c])

_VIRTUAL = dict(_all_virtual(MATCODE_CATALOG))


def _collect_segment_keys(node):
    """节点下所有叶子段 key（含自身若为段叶子的字符串子）。"""
    out = []
    for c in node["children"]:
        if isinstance(c, str):
            out.append(c)
        else:
            out.extend(_collect_segment_keys(c))
    return out


def segment_keys_for(scope: str) -> Optional[List[str]]:
    """把任意分类 scope（大类 key / 中类 key / 段 key）展开为段 key 列表。
    传段 key 本身 → [该 key]；未知 scope → None。排序稳定（按树序）。"""
    if scope in _VIRTUAL:
        return _collect_segment_keys(_VIRTUAL[scope])
    # 叶子段 key
    if any(scope in _collect_segment_keys(t) for t in MATCODE_CATALOG):
        return [scope]
    return None


def top_key_of_segment(seg_key: str) -> Optional[str]:
    """段 key → 所属顶层大类 key（沿树查；兼容 legacy 旧段）。"""
    for t in MATCODE_CATALOG:
        if seg_key in _collect_segment_keys(t):
            return t["key"]
    return None


def top_labels() -> List[dict]:
    """顶层节点（供 /catalog 组树）。"""
    return [{"key": t["key"], "label": t["label"]} for t in MATCODE_CATALOG]
